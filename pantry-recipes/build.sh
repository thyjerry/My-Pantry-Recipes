#!/bin/bash
# Pantry Recipes - Gradle-free build: recipe compiler + tests -> aapt2 -> javac -> d8 -> zipalign -> apksigner
set -euo pipefail
cd "$(dirname "$0")"
export JAVA_HOME=${JAVA_HOME:-$HOME/android/jdk-17.0.21+9}; export PATH=$JAVA_HOME/bin:$PATH
SDK=${ANDROID_HOME:-$HOME/android/sdk}; BT=$SDK/build-tools/34.0.0; JAR=$SDK/platforms/android-34/android.jar
VERSION_NAME=$(sed -n 's/^versionName=//p' version.properties | tr -d '[:space:]')
VERSION_CODE=$(sed -n 's/^versionCode=//p' version.properties | tr -d '[:space:]')
[ -n "$VERSION_NAME" ] && [ -n "$VERSION_CODE" ] || { echo "version.properties needs versionName and versionCode"; exit 1; }
echo "== My Pantry Recipes $VERSION_NAME (versionCode $VERSION_CODE): legacy + modern APKs"
rm -rf build && mkdir -p build/core
[ -f debug.keystore ] || keytool -genkeypair -keystore debug.keystore -storepass android -keypass android \
  -alias androiddebugkey -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Pantry Recipes Debug,O=Pantry Recipes,C=US"

echo "== recipes.json + test harness (JDK)"
javac -nowarn -d build/core src/org/pantryrecipes/app/core/*.java tools/RecipeTool.java tools/V20Tests.java tools/V201Tests.java tools/V21Tests.java tools/V22Tests.java tools/V22More.java
java -cp build/core RecipeTool recipes assets/recipes.json
python3 tools/chunk_recipes.py assets/recipes.json build/apkassets

echo "== icons"
[ -f res/mipmap-mdpi/ic_launcher.png ] || python3 tools/make_icons.py

MODERN_XML='        <provider android:name=".CardProvider" android:authorities="org.pantryrecipes.app.modern.cards"
            android:exported="false" android:grantUriPermissions="true" />'
# flavor: legacy = org.pantryrecipes.app, minSdk 21 (Fire HD 8 / Android 5.1); modern = org.pantryrecipes.app.modern, minSdk 26
build_flavor() {
  local F=$1 PKG MIN TGT PJAR MOD B=build/$1
  if [ "$F" = modern ]; then PKG=org.pantryrecipes.app.modern; MIN=26; TGT=35; PJAR=$SDK/platforms/android-36/android.jar; MOD=true
  else PKG=org.pantryrecipes.app; MIN=21; TGT=34; PJAR=$JAR; MOD=false; fi
  echo "== [$F] $PKG minSdk $MIN targetSdk $TGT"
  mkdir -p $B/res $B/gen/org/pantryrecipes/app $B/classes $B/dex
  printf 'package org.pantryrecipes.app;\n/** Generated by build.sh. */\nfinal class Flavor { private Flavor() { } static final boolean MODERN = %s; }\n' $MOD > $B/gen/org/pantryrecipes/app/Flavor.java
  if [ "$F" = modern ]; then
    python3 - "$B" "$MODERN_XML" <<'PY'
import sys
b, extra = sys.argv[1], sys.argv[2]
s = open('AndroidManifest.xml').read().replace('<!--MODERN-->', extra.strip())
s = s.replace('android:usesCleartextTraffic="false">', 'android:usesCleartextTraffic="false"\n        android:localeConfig="@xml/locales_config">', 1)
s = s.replace('<category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>',
              '<category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n'
              '            <meta-data android:name="android.app.shortcuts" android:resource="@xml/shortcuts" />', 1)
open(b + '/AndroidManifest.xml', 'w').write(s)
PY
    $BT/aapt2 compile --dir res -o $B/res/res.zip
    $BT/aapt2 compile --dir res-modern -o $B/res/modern.zip
    RES="$B/res/res.zip -R $B/res/modern.zip"
  else
    sed 's|<!--MODERN-->||' AndroidManifest.xml > $B/AndroidManifest.xml
    $BT/aapt2 compile --dir res -o $B/res/res.zip
    RES="$B/res/res.zip"
  fi
  $BT/aapt2 link -I $PJAR --manifest $B/AndroidManifest.xml -A build/apkassets --java $B/gen -o $B/unsigned.apk \
    $RES --auto-add-overlay --rename-manifest-package $PKG --custom-package org.pantryrecipes.app \
    --min-sdk-version $MIN --target-sdk-version $TGT --version-code "$VERSION_CODE" --version-name "$VERSION_NAME"
  javac -nowarn -Xlint:-options --release 8 -classpath $PJAR -d $B/classes $(find src $B/gen -name '*.java')
  $BT/d8 --release --min-api $MIN --lib $PJAR --output $B/dex $(find $B/classes -name '*.class')
  python3 -c "import zipfile,sys; zipfile.ZipFile(sys.argv[1],'a',zipfile.ZIP_DEFLATED).write(sys.argv[2],'classes.dex')" $B/unsigned.apk $B/dex/classes.dex
  $BT/zipalign -f -p 4 $B/unsigned.apk $B/aligned.apk
  $BT/apksigner sign --ks debug.keystore --ks-pass pass:android --key-pass pass:android --min-sdk-version $MIN \
    --v1-signing-enabled true --v2-signing-enabled true --v4-signing-enabled false --out $B/signed.apk $B/aligned.apk
  $BT/apksigner verify $B/signed.apk
}
build_flavor legacy
build_flavor modern
# dist/ holds only the current versioned APKs
rm -rf dist && mkdir -p dist
cp build/legacy/signed.apk "dist/MyPantryRecipes-v$VERSION_NAME-legacy.apk"
cp build/modern/signed.apk "dist/MyPantryRecipes-v$VERSION_NAME-modern.apk"
ls -l dist
