import org.pantryrecipes.app.core.*;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.*;

/** v2.0.1 build step + checks: writes assets/medflags.txt (precomputed diet-guide flags), then tests the v2.0.1 fixes. */
public class V201Tests {
    static void check(boolean ok, String m) { RecipeTool.check(ok, m); }
    static void eq(Object e, Object g, String m) { RecipeTool.eq(e, g, m); }

    static String read(File f) throws Exception { return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8); }

    public static void run(List<Recipe> parsed, File root) throws Exception {
        // ---- build step: precompute the medical-guide flags for every bundled recipe ----
        long t0 = System.nanoTime();
        StringBuilder sb = new StringBuilder("# My Pantry Recipes v2.0.1 diet-guide flags (generated by RecipeTool; do not edit)\n"
                + "# id<TAB>flags<TAB>ingredient count. Flags: K potassium, P phosphorus, S sodium, F saturated fat, G added sugar, C high-carb,\n"
                + "# each followed by ingredient indexes. A guide from ingredient names, not medical advice.\n");
        int[] perCode = new int[6];
        for (Recipe r : parsed) {
            int[][] f = MedGuides.compute(r);
            for (int c = 0; c < 6; c++) if (f[c].length > 0) perCode[c]++;
            sb.append(r.id).append('\t').append(MedGuides.encode(f)).append('\t').append(r.ingredients.size()).append('\n');
        }
        long ms = (System.nanoTime() - t0) / 1000000;
        File asset = new File(root, "assets/medflags.txt");
        Files.write(asset.toPath(), sb.toString().getBytes(StandardCharsets.UTF_8));
        System.out.println("medflags.txt: " + parsed.size() + " recipes, " + sb.length() + " chars, " + ms + " ms; recipes per flag K/P/S/F/G/C = " + Arrays.toString(perCode));

        // ---- precomputed == runtime ----
        Map<String, String[]> pre = MedGuides.parse(read(asset));
        eq(parsed.size(), pre.size(), "medflags covers every bundled recipe");
        int same = 0;
        for (Recipe r : parsed) if (MedGuides.encode(MedGuides.flags(r, pre)).equals(MedGuides.encode(MedGuides.compute(r)))) same++;
        eq(parsed.size(), same, "precomputed flags equal runtime flags");
        for (int c = 0; c < 6; c++) check(perCode[c] > 20 && perCode[c] < parsed.size(), "flag " + MedGuides.CODES.charAt(c) + " is selective (" + perCode[c] + ")");
        int[][] rt = MedGuides.decode("K0.3 P2 S5");
        eq("K0.3 P2 S5", MedGuides.encode(rt), "encode/decode round trip");
        eq("", MedGuides.encode(MedGuides.decode("X1 K P? ")), "decode ignores junk");

        // ---- word rules ----
        String[][] yes = {{"potato", "K"}, {"cherry tomatoes", "K"}, {"avocado", "K"}, {"spinach", "K"}, {"banana", "K"}, {"red lentils", "K"}, {"chickpeas", "P"},
                {"milk", "P"}, {"cheddar", "P"}, {"almonds", "P"}, {"bacon", "S"}, {"soy sauce", "S"}, {"chicken stock", "S"}, {"butter", "F"}, {"double cream", "F"},
                {"coconut milk", "F"}, {"sugar", "G"}, {"honey", "G"}, {"maple syrup", "G"}, {"rice", "C"}, {"spaghetti", "C"}, {"flour", "C"}, {"potato", "C"}};
        for (String[] y : yes) {
            Recipe r = one(y[0], 1, "");
            int c = MedGuides.CODES.indexOf(y[1]);
            check(MedGuides.compute(r)[c].length == 1, y[0] + " flagged " + y[1]);
        }
        String[][] no = {{"peanut butter", "F"}, {"butter beans", "F"}, {"butternut squash", "F"}, {"cream of tartar", "F"}, {"coconut milk", "K"}, {"coconut milk", "P"},
                {"olive oil", "S"}, {"sugar snap peas", "G"}, {"lemon juice", "G"}, {"soy sauce", "K"}, {"cocoa butter", "P"}, {"cucumber", "K"}, {"chicken breast", "F"}};
        for (String[] y : no) {
            Recipe r = one(y[0], 1, "");
            int c = MedGuides.CODES.indexOf(y[1]);
            check(MedGuides.compute(r)[c].length == 0, y[0] + " not flagged " + y[1]);
        }
        // added salt: more than 1/4 tsp per serving flags the salt line as high-sodium
        Recipe salty = one("salt", 2, "tsp"); salty.servings = 4;
        eq(1, MedGuides.compute(salty)[2].length, "2 tsp salt / 4 servings flagged");
        eq(1150.0, MedGuides.saltSodiumMg(salty), "salt sodium mg");
        Recipe light = one("salt", 1, "tsp"); light.servings = 4;
        eq(0, MedGuides.compute(light)[2].length, "1/4 tsp per serving not flagged");
        check(Double.isNaN(MedGuides.saltSodiumMg(one("salt", Double.NaN, ""))), "salt to taste = NaN");

        // ---- lines, guides, disclaimer ----
        Recipe mix = new Recipe(); mix.id = "t:1"; mix.title = "t"; mix.servings = 2;
        mix.ingredients.add(new Ingredient("Potato", 500, "g", false));
        mix.ingredients.add(new Ingredient("Milk", 200, "ml", false));
        mix.ingredients.add(new Ingredient("Butter", 30, "g", false));
        mix.ingredients.add(new Ingredient("Salt", 1, "tsp", false));
        int[][] mf = MedGuides.compute(mix);
        List<String> renal = MedGuides.lines(mix, mf, MedGuides.RENAL);
        eq(Arrays.asList("contains high-potassium ingredients: potato, milk", "contains high-phosphorus ingredient: milk", "contains high-sodium ingredient: salt"), renal, "renal lines");
        eq(Arrays.asList("contains high-sodium ingredient: salt", "contains high saturated fat ingredient: butter"), MedGuides.lines(mix, mf, MedGuides.CARDIAC), "cardiac lines");
        eq(Arrays.asList("contains high-carb ingredient: potato"), MedGuides.lines(mix, mf, MedGuides.DIABETIC), "diabetic lines");
        check(!MedGuides.noFlags(mf, MedGuides.RENAL) && MedGuides.noFlags(MedGuides.compute(one("cucumber", 1, "")), MedGuides.RENAL), "noFlags");
        eq("This is a general guide, not medical advice. Limits are different for every person and stage of illness. Follow the plan from your doctor or dietitian.",
                MedGuides.DISCLAIMER, "disclaimer text");
        StringBuilder all = new StringBuilder(MedGuides.DISCLAIMER + MedGuides.DATA_NOTE);
        for (String g : MedGuides.IDS) all.append(MedGuides.RULES.get(g)).append(MedGuides.name(g));
        all.append(MedGuides.estimateLines(mix, 40, MedGuides.IDS, 500, 30)).append(renal);
        String low = all.toString().toLowerCase(Locale.US);
        for (String bad : new String[]{"safe", "certif", "treat", "\\bcures?\\b", "approved", "recommended"}) check(!java.util.regex.Pattern.compile(bad).matcher(low).find(), "no claim word: " + bad);
        check(MedGuides.DATA_NOTE.contains("estimate") && MedGuides.DATA_NOTE.contains("Potassium, phosphorus"), "data note is honest about estimates");
        eq(Arrays.asList("Added salt alone \u2248 1150 mg sodium per serving (estimate; other ingredients add more) \u2013 above your 500 mg per meal limit.",
                "Carbs \u2248 40 g per serving (estimate) \u2013 above your 30 g per meal limit."), MedGuides.estimateLines(mix, 40, MedGuides.IDS, 500, 30), "estimate lines + limits");
        eq(Arrays.asList("Carbs per serving: no estimate (too few ingredients matched)."), MedGuides.estimateLines(mix, Double.NaN, Arrays.asList(MedGuides.DIABETIC), 0, 0), "no carbs estimate");
        eq(20000, MedGuides.clampSodium(999999), "clamp sodium"); eq(0, MedGuides.clampCarbs(-5), "clamp carbs");

        // ---- backup keys ----
        check(Backup.SETTINGS.containsAll(Arrays.asList("medGuides", "medSodiumMg", "medCarbsG")), "backup knows medical-guide keys");
        Backup.Data bd = Backup.parse("{\"app\":\"Pantry Recipes\",\"format\":2,\"settings\":{\"medGuides\":[\"renal\",\"x\",\"renal\",\"diabetic\"],\"medSodiumMg\":1500.4,\"medCarbsG\":-3}}");
        eq(Arrays.asList("renal", "diabetic"), bd.settings.get("medGuides"), "backup guides sanitized");
        eq(1500, bd.settings.get("medSodiumMg"), "backup sodium"); eq(0, bd.settings.get("medCarbsG"), "backup carbs clamped");

        // ---- fruits (v2.0.1) ----
        int fruit = Arrays.asList(Catalog.CATEGORIES).indexOf("Fruits");
        check(fruit >= 0, "Fruits category");
        for (String f : new String[]{"Tomato", "Cherry tomatoes", "Cucumber", "Avocado"}) eq(fruit, Diets.category(Normalizer.normalize(f)), f + " is in Fruits");
        for (String v : new String[]{"Bell pepper", "Eggplant", "Zucchini", "Pumpkin", "Olives"}) {
            int c = Diets.category(Normalizer.normalize(v));
            check(c != fruit, v + " stays out of Fruits (user decision pending), got " + c);
        }
        check(!V20Tests.hasField(Inventory.class, "KITS"), "starter kits are gone");

        // ---- source-level regression guards for the Android UI fixes ----
        File src = new File(root, "src/org/pantryrecipes/app");
        String main = read(new File(src, "MainActivity.java")), ui = read(new File(src, "Ui.java")), v20 = read(new File(src, "V20.java")), v17 = read(new File(src, "V17.java"));
        String mfb = body(main, "List<Matcher.Result> matchFiltered()");
        check(mfb.contains("dMealPasses") && !mfb.contains("methodFilter") && !mfb.contains(" mealPasses(") && !mfb.contains("passesFilters"), "Discover lists ignore the Recipes filters");
        String lf = body(main, "List<Matcher.Result> likeFavorites(");
        check(lf.contains("dMealPasses") && !lf.contains(" mealPasses("), "Based on your favorites uses Discover's own filter");
        String sub = body(main, "List<Matcher.Result> mealFilter(");
        check(sub.contains("dMealPasses") && sub.contains("dMealHidden"), "Discover sub-lists use Discover's own filter");
        check(main.contains("mealFilters(0, this::refreshDiscover, true)"), "Discover meal bar edits Discover state");
        check(!v17.contains("Discover lists are filtered"), "no 'filtered in Recipes' note on Discover");
        check(ui.contains("setOnApplyWindowInsetsListener") && ui.contains("getDisplayCutout") && ui.contains("Build.VERSION.SDK_INT >= 28"), "window insets + guarded cutout");
        for (String act : new String[]{"MainActivity", "CookActivity", "SubsActivity", "AppearanceActivity"})
            check(read(new File(src, act + ".java")).contains("Ui.styleWindow("), act + " handles window insets");
        String chip = body(ui, "static TextView chip(");
        check(chip.contains("setSingleLine(false)") && chip.contains("setMaxLines(3)") && !chip.contains("setSingleLine(true)"), "chips wrap long names");
        check(v20.contains("Suggested from your device language. This app never uses your location."), "region step says device language, never location");
        check(!v20.contains("kitsDialog"), "no starter-kit dialog");
        String manifest = read(new File(root, "AndroidManifest.xml"));
        check(!manifest.contains("LOCATION"), "no location permission");
        Properties vp = new Properties(); vp.load(new java.io.StringReader(read(new File(root, "version.properties"))));
        eq("2.1", vp.getProperty("versionName"), "versionName"); eq("14", vp.getProperty("versionCode"), "versionCode");

        // ---- timing on the JDK (the Fire HD 8 reads medflags.txt instead) ----
        long t1 = System.nanoTime();
        int none = 0;
        for (Recipe r : parsed) if (MedGuides.noFlags(MedGuides.flags(r, pre), MedGuides.RENAL)) none++;
        System.out.println("renal 'no flags' list from medflags: " + none + " recipes in " + (System.nanoTime() - t1) / 1000000 + " ms");
    }

    static Recipe one(String name, double amt, String unit) {
        Recipe r = new Recipe(); r.id = "t:x"; r.title = "t"; r.servings = 1;
        r.ingredients.add(new Ingredient(name, amt, unit, false));
        return r;
    }

    /** The text of a method from its signature to the matching closing brace. */
    static String body(String src, String sig) {
        int i = src.indexOf(sig);
        if (i < 0) return "";
        int b = src.indexOf('{', i), d = 0;
        for (int j = b; j < src.length(); j++) {
            char ch = src.charAt(j);
            if (ch == '{') d++;
            else if (ch == '}' && --d == 0) return src.substring(i, j + 1);
        }
        return src.substring(i);
    }
}
