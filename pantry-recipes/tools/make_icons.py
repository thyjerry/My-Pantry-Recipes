#!/usr/bin/env python3
"""v1.8: My Pantry Recipes launcher icons, redrawn from the supplied logo: a flat green circle with a white leaf
(transparent outside the circle). The leaf outline was traced once from the logo and is kept here as polygons in
circle units (centre 0,0, radius 1), so the icons are rendered cleanly at any size. Usage: make_icons.py [res dir]"""
from PIL import Image, ImageDraw
import os, sys

GREEN = (19, 174, 72)
WHITE = (255, 255, 255)
LEAF_POLYGONS = None  # filled in below

def leaf_points(size, scale=1.0, cx=None, cy=None):
    cx = size / 2 if cx is None else cx
    cy = size / 2 if cy is None else cy
    r = size / 2 * scale
    return [[(cx + x * r, cy + y * r) for x, y in poly] for poly in LEAF_POLYGONS]

def render(size, circle=True, bg=None, leaf_scale=1.0):
    """The mark at size x size: green circle (or a full-bleed bg colour) with the white leaf, 8x supersampled."""
    S = size * 8
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0) if bg is None else bg + (255,))
    d = ImageDraw.Draw(img)
    if circle:
        d.ellipse([0, 0, S - 1, S - 1], fill=GREEN + (255,))
    for poly in leaf_points(S, leaf_scale):
        d.polygon(poly, fill=WHITE + (255,))
    return img.resize((size, size), Image.LANCZOS)

def save_small(img, path):
    """Palette PNG (the mark has two colours plus anti-aliased edges, so 48 colours lose nothing visible)."""
    img.quantize(colors=48, method=Image.FASTOCTREE, dither=Image.NONE).save(path, optimize=True)

def svg_path(scale=1.0, vb=24.0):
    """The leaf as SVG / VectorDrawable path data in a vb x vb box (circle radius vb/2)."""
    c, r = vb / 2, vb / 2 * scale
    f = lambda p: "%.2f,%.2f" % (c + p[0] * r, c + p[1] * r)
    out = []
    for seg in LEAF:
        out.append(seg[0] + " ".join(f(p) for p in seg[1:]))
    return "".join(out) + "Z"

# The leaf outline as cubic Bezier segments in circle units, fitted to the logo (max error ~2 % of the radius).
LEAF = [
    ("M", (-0.556, -0.557)),
    ("C", (0.0447, -0.2582), (0.6049, -0.2099), (0.3706, 0.6147)),   # outer right edge down to the stem
    ("L", (0.3603, 0.6147)),                                          # stem foot
    ("C", (0.2826, 0.1906), (-0.0182, 0.0722), (-0.3176, -0.1795)),   # vein, right side, up to its tip
    ("C", (-0.1186, 0.1006), (0.2112, 0.2206), (0.2588, 0.6147)),     # vein, left side, back down
    ("L", (0.2132, 0.6206)),                                          # blade foot
    ("C", (-0.4428, 0.566), (-0.6454, 0.0057), (-0.556, -0.557)),    # outer left edge back to the tip
]

def _flatten(n=120):
    pts, cur = [], None
    for seg in LEAF:
        if seg[0] in ("M", "L"):
            cur = seg[1]; pts.append(cur)
        else:
            p0, (p1, p2, p3) = cur, seg[1:]
            for k in range(1, n + 1):
                t = k / n; u = 1 - t
                pts.append((u**3*p0[0] + 3*u*u*t*p1[0] + 3*u*t*t*p2[0] + t**3*p3[0],
                            u**3*p0[1] + 3*u*u*t*p1[1] + 3*u*t*t*p2[1] + t**3*p3[1]))
            cur = p3
    return pts

LEAF_POLYGONS = [_flatten()]

if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else "res"
    for name, px in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)]:
        os.makedirs(f"{root}/mipmap-{name}", exist_ok=True)
        # a 4 % margin, like other legacy launcher icons
        icon = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        inner = int(round(px * 0.92))
        icon.alpha_composite(render(inner), ((px - inner) // 2, (px - inner) // 2))
        save_small(icon, f"{root}/mipmap-{name}/ic_launcher.png")
    save_small(render(512), "icon-512.png")
    # header logo: a VectorDrawable (no bitmap), drawn once in the header band
    os.makedirs(f"{root}/drawable", exist_ok=True)
    with open(f"{root}/drawable/ic_logo.xml", "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- v1.8: My Pantry Recipes mark, generated by tools/make_icons.py -->\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp"\n'
                '    android:viewportWidth="24" android:viewportHeight="24">\n'
                '    <path android:fillColor="#13AE48" android:pathData="M12,0A12,12 0,1 1,12,24A12,12 0,1 1,12,0Z"/>\n'
                '    <path android:fillColor="#FFFFFF" android:pathData="%s"/>\n</vector>\n' % svg_path())
    print("icons written")
