import org.pantryrecipes.app.core.*;

import java.io.File;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.*;

/**
 * v2.0.1 web port data: writes js/data201.js (diet-guide word lists, texts and the precomputed flags from the Android
 * assets/medflags.txt) and tests/vectors201.json (estimate lines for sample recipes and limits).
 * Usage: java -cp build V201Export <android project dir> <web dir>
 */
public class V201Export {
    static String read(File f) throws Exception { return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8); }

    @SuppressWarnings("unchecked")
    static List<Object> list(String name) throws Exception {
        Field f = MedGuides.class.getDeclaredField(name);
        f.setAccessible(true);
        List<Object> l = new ArrayList<Object>((Set<String>) f.get(null));
        Collections.sort((List) l);
        return l;
    }

    public static void main(String[] a) throws Exception {
        File android = new File(a[0]), web = new File(a[1]);
        Map<String, Object> d = new LinkedHashMap<String, Object>();
        for (String n : new String[]{"HIGH_K", "NOT_K", "HIGH_P", "NOT_P", "HIGH_SATFAT", "NOT_SATFAT"}) d.put(n, list(n));
        Field lf = MedGuides.class.getDeclaredField("LABELS"); lf.setAccessible(true);
        d.put("labels", new ArrayList<Object>(Arrays.asList((Object[]) lf.get(null))));
        d.put("ids", new ArrayList<Object>(MedGuides.IDS));
        d.put("names", new ArrayList<Object>(MedGuides.NAMES));
        d.put("rules", new LinkedHashMap<String, Object>(MedGuides.RULES));
        d.put("disclaimer", MedGuides.DISCLAIMER);
        d.put("dataNote", MedGuides.DATA_NOTE);
        d.put("flags", read(new File(android, "assets/medflags.txt")));
        Files.write(new File(web, "js/data201.js").toPath(), ("/* Generated by tools/V201Export.java from the Android core; do not edit. A guide, not medical advice. */\n"
                + "(typeof self !== 'undefined' ? self : globalThis).PR_DATA201 = " + Json.write(d) + ";\n").getBytes(StandardCharsets.UTF_8));

        List<Recipe> recipes = Recipe.parseList(read(new File(android, "assets/recipes.json")));
        Map<String, Nutrition.Food> foods = Nutrition.parse(read(new File(android, "assets/foods.tsv")));
        List<Object> est = new ArrayList<Object>();
        int[][] lims = {{0, 0}, {500, 45}, {2000, 120}};
        for (int i = 0; i < recipes.size(); i += 37) {
            Recipe r = recipes.get(i);
            Nutrition.Estimate e = Nutrition.estimate(r, foods);
            double cb = e.show() ? e.carbs : Double.NaN;
            int[] lm = lims[i % 3];
            Map<String, Object> m = new LinkedHashMap<String, Object>();
            m.put("id", r.id); m.put("na", lm[0]); m.put("cb", lm[1]);
            m.put("lines", new ArrayList<Object>(MedGuides.estimateLines(r, cb, MedGuides.IDS, lm[0], lm[1])));
            int[][] f = MedGuides.compute(r);
            List<Object> gl = new ArrayList<Object>();
            for (String g : MedGuides.IDS) gl.add(new ArrayList<Object>(MedGuides.lines(r, f, g)));
            m.put("guideLines", gl);
            est.add(m);
        }
        Map<String, Object> v = new LinkedHashMap<String, Object>();
        v.put("samples", est);
        Files.write(new File(web, "tests/vectors201.json").toPath(), Json.write(v).getBytes(StandardCharsets.UTF_8));
        System.out.println("data201.js + vectors201.json: " + est.size() + " samples");
    }
}
