import org.pantryrecipes.app.core.*;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.*;

/**
 * v2.0 web port data and reference results. Writes js/data20.js (region names, cuisine groups, BLS
 * price table) and tests/vectors20.json (diet tags for every bundled recipe, region names, prices, editor output).
 * Usage: java -cp build V20Export <android project dir> <web dir>
 */
public class V20Export {
    static List<Object> L(Object... a) { return new ArrayList<Object>(Arrays.asList(a)); }
    static String read(File f) throws Exception { return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8); }

    static final String[] TEXTS = {"2 zucchini, sliced", "Courgette and aubergine bake", "1 cup heavy cream", "Preheat the broiler and line with parchment paper.",
            "HEAVY WHIPPING CREAM", "Shrimp scampi", "1 lb ground beef", "Cilantro lime rice", "Add the bell peppers", "Fry in a skillet with green onions",
            "superfine sugar", "Powdered Sugar glaze", "corn on the cob", "melon salad", "Grill the cantaloupe", "", "Nothing to change here",
            "Self-rising flour and baking soda", "scallions", "Beets & beetroot", "Cover with plastic wrap", "Golden raisins", "light corn syrup", "sweetcorn fritters",
            "pepper", "Peppercorns", "zucchinis", "cookies and biscuits", "Arugula, rocket", "jumbo shrimp, shrimp"};
    static final String[] LINES = {"1 1/2 cups milk", "2 eggs", "salt, optional", "1/2 tsp salt", "200 g plain flour", "3 tbsp olive oil", "- 1 onion, chopped",
            "\u00bd cup sugar", "1-2 cloves garlic", "(optional) parsley", "2 large eggs", "1 c. rice", "1,5 kg potatoes", "Pinch of salt", "   ", "1 can (400 g) tomatoes",
            "2. 3 carrots", "optional: chili flakes", "4 medium", "12 oz spaghetti", "1 (14 oz) can chickpeas", "3/4 cup water", "10 small potatoes"};
    static final String[] ZIPS = {"10001", "02139", "60601", "73301", "94105", "99501", "96813", "00601", "abcde", "1234", "33101-1234", "20500", "56901", "88510", "", "57001"};
    static final String[] TAGS = {"en-US", "en-GB", "en_IE", "fr-FR", "de", "en", "es-MX", "pt-BR", "en-AU", "en-NZ", "fr-CA", "ja-JP", "zh", "nl-BE", "ga", null};

    public static void main(String[] a) throws Exception {
        File android = new File(a[0]), web = new File(a[1]);
        List<Recipe> recipes = Recipe.parseList(read(new File(android, "assets/recipes.json")));
        Map<String, Nutrition.Food> foods = Nutrition.parse(read(new File(android, "assets/foods.tsv")));
        String bls = read(new File(android, "assets/bls-prices.tsv"));
        Map<String, Cost.Price> est = Cost.parseDefaults(read(new File(android, "assets/prices.tsv")));

        // ---------- data20.js ----------
        Map<String, Object> d = new LinkedHashMap<String, Object>();
        // v2.0.1: starter kits removed (no "kits" key)
        List<Object> terms = new ArrayList<Object>();
        for (String[] row : Region.terms()) terms.add(new ArrayList<Object>(Arrays.asList((Object[]) row)));
        d.put("terms", terms);
        Map<String, Object> cu = new LinkedHashMap<String, Object>();
        cu.put("groups", new ArrayList<Object>(Cuisines.GROUPS));
        List<Object> data = new ArrayList<Object>();
        for (String g : Cuisines.GROUPS) { List<Object> row = L(g); row.addAll(Cuisines.inGroup(g)); data.add(row); }
        cu.put("data", data);
        cu.put("lumps", new ArrayList<Object>(Cuisines.LUMPS));
        d.put("cuisines", cu);
        d.put("bls", bls);
        String js = "/* Generated by tools/V20Export.java from the Android core; do not edit. BLS prices: public domain (U.S. Bureau of Labor Statistics). */\n"
                + "window.PR_DATA20 = " + Json.write(d) + ";\n";
        Files.write(new File(web, "js/data20.js").toPath(), js.getBytes(StandardCharsets.UTF_8));
        // ---------- helpers20.js (Stage 2 kitchen helpers: raw text, parsed lazily by PR.Helpers20) ----------
        String htxt = new String(Files.readAllBytes(new File(android, "assets/helpers20.txt").toPath()), StandardCharsets.UTF_8);
        Files.write(new File(web, "js/helpers20.js").toPath(), ("// Generated by tools/V20Export.java from the Android assets/helpers20.txt. Do not edit.\n(typeof self !== 'undefined' ? self : globalThis).PR_HELPERS20 = "
                + Json.write(htxt) + ";\n").getBytes(StandardCharsets.UTF_8));

        // ---------- vectors20.json ----------
        Map<String, Object> v = new LinkedHashMap<String, Object>();
        Map<String, Object> diets = new LinkedHashMap<String, Object>();
        for (Recipe r : recipes) diets.put(r.id, new ArrayList<Object>(Diets.classify(r, foods)));
        v.put("diets", diets);
        org.pantryrecipes.app.core.Helpers20 h20 = org.pantryrecipes.app.core.Helpers20.parse(htxt);
        Map<String, Object> hv = new LinkedHashMap<String, Object>();
        hv.put("counts", h20.equivs.size() + "," + h20.rescues.size() + "," + h20.blends.size() + "," + h20.times.size() + "," + h20.explains.size());
        List<Object> bl = new ArrayList<Object>();
        for (int i = 0; i < h20.blends.size(); i++) {
            StringBuilder sb = new StringBuilder("[");
            for (String[] r : org.pantryrecipes.app.core.Helpers20.build(h20.blends.get(i), null, 12, i % 2 == 0, i % 3 == 0)) sb.append(sb.length() > 1 ? "," : "").append(Json.write(r[0]));
            bl.add(sb.append("]").toString());
        }
        hv.put("blends", bl);
        v.put("helpers", hv);
        List<Object> blk = new ArrayList<Object>();
        for (int i = 0; i < recipes.size(); i += 97) for (String id : Diets.IDS) {
            List<String> b = Diets.blockers(recipes.get(i), id);
            if (!b.isEmpty()) blk.add(L(recipes.get(i).id, id, new ArrayList<Object>(b)));
        }
        v.put("blockers", blk);

        List<Object> loc = new ArrayList<Object>();
        for (String region : Region.IDS) for (String t : TEXTS) loc.add(L(region, t, Region.localize(t, region, false), Region.localize(t, region, true)));
        v.put("localize", loc);
        List<Object> guess = new ArrayList<Object>();
        for (String t : TAGS) guess.add(L(t, Region.guess(t)));
        v.put("guess", guess);
        Map<String, Object> defs = new LinkedHashMap<String, Object>();
        for (String region : Region.IDS) {
            Region.Defaults x = Region.defaults(region);
            Map<String, Object> m = new LinkedHashMap<String, Object>();
            m.put("units", x.units); m.put("weightUnit", x.weightUnit); m.put("currency", x.currency); m.put("dateFormat", x.dateFormat);
            m.put("priceSource", x.priceSource); m.put("showCups", x.showCups); m.put("gasMarks", x.gasMarks); m.put("fanNote", x.fanNote);
            m.put("decimalComma", x.decimalComma); m.put("cup250", x.cup250); m.put("clock24", x.clock24); m.put("weekStartsSunday", x.weekStartsSunday);
            m.put("allergens", new ArrayList<Object>(x.allergens));
            List<Object> labels = new ArrayList<Object>();
            for (String id : Allergens.ALL_IDS) labels.add(Region.allergenLabel(id, region));
            m.put("labels", labels);
            m.put("listName", Region.allergenListName(region));
            m.put("holidays", new ArrayList<Object>(Region.holidayDefaults(region)));
            m.put("date", Region.formatDate("2026-03-07", x.dateFormat));
            m.put("time", Region.formatTime(18 * 60 + 5, x.clock24) + "|" + Region.formatTime(5, x.clock24) + "|" + Region.formatTime(12 * 60, x.clock24));
            m.put("week", Region.weekStart("2026-10-28", x.weekStartsSunday) + "|" + Region.weekStart("2026-11-01", x.weekStartsSunday));
            m.put("money", Region.money(x.currency, 3.5, x.decimalComma));
            defs.put(region, m);
        }
        v.put("regions", defs);

        List<Object> zips = new ArrayList<Object>();
        for (String z : ZIPS) zips.add(L(z, RegionalPrices.cleanZip(z), RegionalPrices.state(z), RegionalPrices.region(z)));
        v.put("zips", zips);
        RegionalPrices.Table t = RegionalPrices.parse(bls);
        Map<String, Object> pr = new LinkedHashMap<String, Object>();
        for (String region : RegionalPrices.REGIONS) {
            Map<String, RegionalPrices.Source> src = new LinkedHashMap<String, RegionalPrices.Source>();
            Map<String, Cost.Price> p = RegionalPrices.defaults(t, region, est, src);
            List<Object> rows = new ArrayList<Object>();
            for (Map.Entry<String, Cost.Price> e : p.entrySet()) {
                Cost.Price x = e.getValue();
                rows.add(L(e.getKey(), x.price, x.amount, x.unit, src.get(e.getKey()).kind, src.get(e.getKey()).label));
            }
            int[] c = RegionalPrices.coverage(t, region);
            Map<String, Object> m = new LinkedHashMap<String, Object>();
            m.put("factor", t.factor(region)); m.put("coverage", L((long) c[0], (long) c[1])); m.put("rows", rows);
            pr.put(region, m);
        }
        v.put("prices", pr);
        String op = "{\"items\":[{\"price\":2.49,\"currency\":\"USD\",\"date\":\"2026-08-01\",\"location\":{\"osm_name\":\"Store A\",\"osm_address_city\":\"Boston\",\"osm_address_postcode\":\"02139\",\"osm_address_country_code\":\"US\"}},"
                + "{\"price\":2.99,\"currency\":\"USD\",\"date\":\"2026-09-12\",\"location\":{\"osm_name\":\"Store B\",\"osm_address_postcode\":\"94105\",\"osm_address_country_code\":\"US\"}},"
                + "{\"price\":1.5,\"currency\":\"EUR\",\"date\":\"2026-09-12\"},{\"price\":3.1,\"currency\":\"USD\",\"date\":\"2026-07-30\"},"
                + "{\"price\":2.2,\"currency\":\"USD\",\"date\":\"2026-09-01\",\"location\":{\"osm_address_country_code\":\"FR\"}},{\"price\":\"x\"},{\"price\":-1,\"currency\":\"USD\",\"date\":\"2026-01-01\"}]}";
        List<Object> ops = new ArrayList<Object>();
        for (String region : new String[]{"US", "NE", "W"}) {
            List<Object> rows = new ArrayList<Object>();
            for (RegionalPrices.OpenPrice p : RegionalPrices.parseOpenPrices(op, region, 10)) rows.add(L(p.price, p.date, p.store, p.city, p.state, p.nearby));
            ops.add(L(region, rows));
        }
        v.put("openPricesJson", op);
        v.put("openPrices", ops);
        v.put("openPricesUrl", L(RegionalPrices.openPricesUrl("0 12345-67890 5"), RegionalPrices.openPricesUrl("123"), RegionalPrices.openPricesUrl(null)));

        // inventory
        List<Object> inv = new ArrayList<Object>();
        String[][] items = {{"chicken breast", "Chicken breast"}, {"ground beef", "Ground beef"}, {"frozen peas", "Frozen peas"}, {"cumin", "Cumin"}, {"oregano", "Dried oregano"},
                {"potato", "Potato"}, {"spinach", "Spinach"}, {"salmon", "Salmon"}, {"bacon", "Bacon"}, {"cheddar", "Cheddar"}, {"butter", "Butter"}, {"rice", "Rice"},
                {"basil", "Basil"}, {"bread", "Bread"}, {"shrimp", "Shrimp"}, {"whole chicken", "Whole chicken"}, {"pork chop", "Pork chop"}, {"milk", "Milk"}};
        for (String[] it : items) inv.add(L(it[0], it[1], Inventory.defaultLocation(it[0], it[1]), (long) Inventory.freezerMonths(it[0]),
                Inventory.useOrTossDate("2026-01-31", it[0]), Inventory.freezerStatus("2026-05-15", it[0], "2026-10-30")));
        v.put("inventory", inv);
        Map<String, Integer> kc = Inventory.keyCounts(recipes);
        List<Object> buy = new ArrayList<Object>();
        for (String[] row : Inventory.spicesToBuy(new HashSet<String>(Arrays.asList("salt", "black pepper", "cumin")), kc, 8)) buy.add(L(row[0], row[1], row[2]));
        v.put("buyNext", buy);
        Recipe ct = Inventory.cookTonight(recipes, new HashSet<String>(Arrays.asList("spinach", "chicken breast")), new HashSet<String>(Arrays.asList("garlic", "onion", "olive oil", "salt")));
        v.put("cookTonight", ct == null ? null : ct.id);

        // cuisines
        List<Object> cg = new ArrayList<Object>();
        for (String c : new String[]{"Jamaican", "jamaican ", "Trinidadian", "Argentinian", "Martian", null, "Italian", "Levantine", "West African"})
            cg.add(L(c, Cuisines.group(c), Cuisines.known(c)));
        v.put("cuisineGroups", cg);

        // editor
        List<Object> lines = new ArrayList<Object>();
        for (String l : LINES) {
            Ingredient i = RecipeEditor.ingredientLine(l);
            lines.add(i == null ? L(l, null) : L(l, i.name, Double.isNaN(i.amount) ? null : i.amount, i.unit, i.optional, RecipeEditor.lineOf(i)));
        }
        v.put("lines", lines);
        RecipeEditor.Draft dr = new RecipeEditor.Draft();
        dr.title = "  Sunday   Stew "; dr.cuisine = "Irish"; dr.prep = 20; dr.cook = 120; dr.servings = 6;
        dr.ingredients = "1 lb beef chuck\n2 carrots\n1 onion\nsalt, optional\n\n2 cups beef stock";
        dr.steps = "1. Brown the beef.\nStep 2: Add the rest.\n\n  Simmer 2 hours.";
        dr.tags = "Winter, family, winter,  Slow  Cook";
        dr.note = "Grandma's.";
        Recipe built = RecipeEditor.build(dr, "u:test1", foods);
        v.put("built", built.toMap());
        v.put("problem", L(RecipeEditor.problem(dr), RecipeEditor.problem(new RecipeEditor.Draft())));
        v.put("share", RecipeEditor.shareText(built, 3));
        Backup.Rating rt = new Backup.Rating(); rt.stars = 4; rt.note = "Less salt <b>";
        Map<String, Backup.Rating> rts = new HashMap<String, Backup.Rating>(); rts.put("u:test1", rt);
        v.put("cookbook", RecipeEditor.cookbookHtml("Smith & Sons' <Book>", L(built, recipes.get(0)).size() == 0 ? null : Arrays.asList(built, recipes.get(0)), rts, "2026-10-30"));
        RecipeEditor.Draft mv = RecipeEditor.myVersion(recipes.get(77));
        v.put("myVersion", L(mv.title, mv.basedOn, mv.ingredients, mv.steps));
        v.put("pack", RecipeEditor.packWrite("Mine", Arrays.asList(built, recipes.get(0)), "2.0", "2026-10-30"));

        // household
        String hh = "[{\"name\":\"  Sam <x> \",\"allergens\":[\"sesame\",\"mustard\",\"bogus\"],\"hide\":true},{\"name\":\"\"},{\"name\":\"Alex\",\"allergens\":[\"gluten\",\"dairy\"]},5]";
        List<Household.Person> ps = Household.parse(Json.parse(hh));
        v.put("householdJson", hh);
        v.put("household", Household.toList(ps));
        List<Object> al = new ArrayList<Object>();
        for (int i = 0; i < recipes.size(); i += 151) al.add(L(recipes.get(i).id, new ArrayList<Object>(Household.alerts(recipes.get(i), ps, "uk"))));
        v.put("alerts", al);

        // backup with v2.0 settings (secrets dropped); sample shared with tools/V20Tests.java
        v.put("backupSample", V20Tests.SAMPLE);
        v.put("backupWrite", Backup.write(Backup.parse(V20Tests.SAMPLE)));

        {
        // ---------- stage3-data.js + Stage 3 vectors (holidays, fasting labels, baking helpers) ----------
        String s3txt = new String(Files.readAllBytes(new File(android, "assets/stage3.txt").toPath()), StandardCharsets.UTF_8);
        Files.write(new File(web, "js/stage3-data.js").toPath(), ("// Generated by tools/V20Export.java from the Android assets/stage3.txt. Do not edit.\n(typeof self !== 'undefined' ? self : globalThis).PR_STAGE3 = "
                + Json.write(s3txt) + ";\n").getBytes(StandardCharsets.UTF_8));
        org.pantryrecipes.app.core.Stage3 s3 = org.pantryrecipes.app.core.Stage3.parse(s3txt);
        Map<String, Object> sv = new LinkedHashMap<String, Object>();
        sv.put("counts", s3.holidays.size() + "," + s3.fasts.size() + "," + s3.trouble.size() + "," + s3.storage.size() + "," + s3.altitude.size() + "," + s3.party.size());
        Map<String, Object> dates = new LinkedHashMap<String, Object>(), secs = new LinkedHashMap<String, Object>(), s3defs = new LinkedHashMap<String, Object>();
        List<String> allIds = new ArrayList<String>();
        for (org.pantryrecipes.app.core.Stage3.Holiday h : s3.holidays) {
            allIds.add(h.id);
            StringBuilder sb = new StringBuilder();
            for (int y = 2025; y <= 2031; y++) sb.append(y > 2025 ? "," : "").append(String.valueOf(org.pantryrecipes.app.core.Stage3.dateIn(h, y)));
            dates.put(h.id, sb.toString());
            StringBuilder ids = new StringBuilder();
            for (Recipe r : s3.section(h, recipes, 60)) ids.append(ids.length() > 0 ? "," : "").append(r.id);
            secs.put(h.id, ids.toString());
            StringBuilder s3dr = new StringBuilder();
            for (String reg : new String[]{"us", "ca", "uk", "eu", "anz", "other", null}) s3dr.append(org.pantryrecipes.app.core.Stage3.defaultOn(h, reg) ? '1' : '0');
            s3defs.put(h.id, s3dr.toString());
        }
        sv.put("dates", dates); sv.put("sections", secs); sv.put("defaults", s3defs);
        Map<String, Object> ups = new LinkedHashMap<String, Object>();
        for (String today : new String[]{"2026-11-02", "2026-12-20", "2027-02-01", "2027-12-30", "2030-09-01"}) {
            StringBuilder sb = new StringBuilder();
            for (org.pantryrecipes.app.core.Stage3.Upcoming u : s3.upcoming(allIds, today, 21)) sb.append(sb.length() > 0 ? "," : "").append(u.h.id).append('@').append(u.date).append('/').append(u.days);
            ups.put(today, sb.toString());
        }
        sv.put("upcoming", ups);
        Map<String, Object> fl = new LinkedHashMap<String, Object>();
        List<String> fids = new ArrayList<String>();
        for (org.pantryrecipes.app.core.Stage3.Fast f : s3.fasts) fids.add(f.id);
        for (Recipe r : recipes) {
            StringBuilder sb = new StringBuilder();
            for (org.pantryrecipes.app.core.Stage3.Fast f : s3.labels(r, fids)) sb.append(sb.length() > 0 ? "," : "").append(f.id);
            if (sb.length() > 0) fl.put(r.id, sb.toString());
        }
        sv.put("fasting", fl);
        List<Object> calc = new ArrayList<Object>();
        double[] bk = org.pantryrecipes.app.core.Stage3.bakers(437, 68.5, 2.2, 0.8, 20);
        StringBuilder cb = new StringBuilder();
        for (double s3d : bk) cb.append(String.format(java.util.Locale.ROOT, "%.4f,", s3d));
        cb.append(String.format(java.util.Locale.ROOT, "%.4f,", org.pantryrecipes.app.core.Stage3.flourFor(900, 72, 2, 0, 25)));
        cb.append(String.format(java.util.Locale.ROOT, "%.6f,", org.pantryrecipes.app.core.Stage3.panFactor(org.pantryrecipes.app.core.Stage3.panArea("round", 20, 0), org.pantryrecipes.app.core.Stage3.panArea("rect", 23, 33))));
        int[] tl = org.pantryrecipes.app.core.Stage3.timeline(22 * 60 + 15, new int[]{15, 60, 600, 50, 45});
        for (int s3t : tl) cb.append(org.pantryrecipes.app.core.Stage3.clock(s3t, false)).append(';');
        cb.append(org.pantryrecipes.app.core.Stage3.startFor(7 * 60, new int[]{45, 120, 30})).append(',');
        for (int c : new int[]{100, 130, 150, 175, 205, 250}) cb.append(org.pantryrecipes.app.core.Stage3.gasMark(c)).append('/');
        for (double ft : new double[]{0, 3000, 4999, 5000, 8000}) { String[] s3a = s3.altitudeFor(ft); cb.append(s3a == null ? "-" : s3a[0]).append('/'); }
        for (String[] s3pr : s3.party) cb.append(org.pantryrecipes.app.core.Stage3.partyNeed(s3pr, 37)).append('/');
        calc.add(cb.toString());
        sv.put("calc", calc);
        try {
            String s3base = org.pantryrecipes.app.core.Backup.write(new org.pantryrecipes.app.core.Backup.Data());
            String s3in = s3base.replace("\"settings\":{}", "\"settings\":{\"holidays\":[\"easter\",\"easter\",\"Bad Id\",\"diwali\",5],\"fasts\":[\"vrat\"],\"holLead\":21,\"holBanner\":false,\"holNotify\":true,\"fastChips\":\"yes\","
                    + "\"starter\":[{\"d\":\"2026-11-02\",\"m\":615,\"ratio\":\"1:2:2\",\"r\":\"ok\",\"x\":1},{\"d\":\"bad\"},7],\"bakeLog\":[{\"d\":\"2026-11-01\",\"what\":\"Loaf\",\"note\":\"\",\"stars\":4.7}],\"holLeadX\":3}");
            sv.put("backupIn", s3in);
            sv.put("backupOut", org.pantryrecipes.app.core.Backup.write(org.pantryrecipes.app.core.Backup.parse(s3in)));
        } catch (Exception s3e) { throw new RuntimeException(s3e); }
        v.put("stage3", sv);
        }
        Files.write(new File(web, "tests/vectors20.json").toPath(), Json.write(v).getBytes(StandardCharsets.UTF_8));
        System.out.println("V20Export: " + recipes.size() + " recipes, data20.js " + js.length() / 1024 + " KB");
    }
}
