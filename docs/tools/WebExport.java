    static List<Object> ids(List<Matcher.Result> l) {
        List<Object> o = new ArrayList<Object>();
        for (Matcher.Result r : l) o.add(r.recipe.id);
        return o;
    }

    // ---- copies of Android-only logic (MealDb.convert/splitSteps and CookActivity.stepMinutes), JDK-friendly ----
    static String s(Map<String, Object> m, String k) {
        Object o = m.get(k);
        return o == null ? "" : String.valueOf(o).trim();
    }

    static Recipe convert(Map<String, Object> m) {
        Recipe r = new Recipe();
        String id = s(m, "idMeal");
        r.id = "m:" + id;
        r.title = s(m, "strMeal");
        r.category = s(m, "strCategory");
        r.cuisine = s(m, "strArea");
        if (r.cuisine.isEmpty() || r.cuisine.equalsIgnoreCase("Unknown")) r.cuisine = s(m, "strCountry");
        r.image = s(m, "strMealThumb");
        r.sourceUrl = s(m, "strSource");
        if (r.sourceUrl.isEmpty()) r.sourceUrl = s(m, "strYoutube");
        r.source = "TheMealDB";
        r.prepMin = -1; r.cookMin = -1; r.servings = 4; r.servingsKnown = false;
        for (int i = 1; i <= 20; i++) {
            String name = s(m, "strIngredient" + i);
            if (name.isEmpty()) continue;
            Quantity.Parsed p = Quantity.parse(s(m, "strMeasure" + i));
            r.ingredients.add(new Ingredient(name, p.amount, p.unit, false));
        }
        r.steps.addAll(splitSteps(s(m, "strInstructions")));
        r.tags.addAll(DietClassifier.classify(r.ingredients));
        r.tagsInferred = true;
        r.meals.addAll(MealType.infer(r.category, r.title));
        return r;
    }

    static List<String> splitSteps(String text) {
        List<String> out = new ArrayList<String>();
        for (String line : text.split("\\r?\\n")) {
            String t = line.trim().replaceFirst("^(?i)(step\\s*\\d+[:.)]?|\\d+[.)]|[-\\u2022*])\\s*", "").trim();
            if (t.length() < 3) continue;
            if (t.matches("(?i)step\\s*\\d+")) continue;
            if (t.length() > 450) {
                String[] sentences = t.split("(?<=[.!?])\\s+");
                StringBuilder b = new StringBuilder();
                for (String sen : sentences) {
                    if (b.length() > 0 && b.length() + sen.length() > 280) { out.add(b.toString().trim()); b.setLength(0); }
                    b.append(sen).append(' ');
                }
                if (b.length() > 0) out.add(b.toString().trim());
            } else out.add(t);
        }
        return out;
    }

    static final Pattern MINUTES = Pattern.compile("(\\d+)(?:\\s*(?:-|to|\u2013)\\s*(\\d+))?\\s*(?:minutes|minute|mins|min)\\b", Pattern.CASE_INSENSITIVE);
    static final Pattern HOURS = Pattern.compile("(\\d+)\\s*(?:hours|hour|hrs|hr)\\b", Pattern.CASE_INSENSITIVE);

    static int stepMinutes(String s) {
        java.util.regex.Matcher m = MINUTES.matcher(s);
        if (m.find()) { int v = Integer.parseInt(m.group(m.group(2) != null ? 2 : 1)); return v > 0 && v <= 600 ? v : 0; }
        java.util.regex.Matcher h = HOURS.matcher(s);
        if (h.find()) { int v = Integer.parseInt(h.group(1)) * 60; return v > 0 && v <= 600 ? v : 0; }
        return 0;
    }
