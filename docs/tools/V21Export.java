import org.pantryrecipes.app.core.*;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.*;

/** v2.1: js/data21.js (botanical fruits, glossary, fun fact) and tests/vectors21.json (category moves) from the Android core. */
public class V21Export {
    public static void main(String[] a) throws Exception {
        File web = new File(a[1]), android = new File(a[0]);
        Map<String, Object> d = new LinkedHashMap<String, Object>();
        List<Object> labels = new ArrayList<Object>(Botany.LABELS);
        Map<String, Object> facts = new LinkedHashMap<String, Object>();
        for (String l : Botany.LABELS) facts.put(Normalizer.normalize(l), Botany.fact(Normalizer.normalize(l)));
        d.put("labels", labels); d.put("facts", facts);
        d.put("term", Botany.GLOSSARY_TERM); d.put("glossary", Botany.GLOSSARY); d.put("funFact", Botany.FUN_FACT);
        String js = "/* Generated by tools/V21Export.java from the Android core (Botany.java). Do not edit. MIT License. */\n"
                + "(typeof self !== 'undefined' ? self : global).PR_DATA21 = " + Json.write(d) + ";\n";
        Files.write(new File(web, "js/data21.js").toPath(), js.getBytes(StandardCharsets.UTF_8));
        Map<String, Object> raw = new LinkedHashMap<String, Object>();
        raw.put("Tomato", "Vegetables"); raw.put("cucumber", "Vegetables"); raw.put("eggplant", "Nope"); raw.put("", "Fruits");
        raw.put("bell pepper", 7); raw.put("Olives", "Fruits"); raw.put("Carrot", "Snacks");
        Map<String, String> mv = Botany.sanitize(raw);
        Map<String, Object> v = new LinkedHashMap<String, Object>();
        v.put("raw", raw); v.put("sanitized", new LinkedHashMap<String, Object>(mv));
        Map<String, Object> secs = new LinkedHashMap<String, Object>(), haves = new LinkedHashMap<String, Object>();
        Set<String> pk = new HashSet<String>(Arrays.asList("tomato", "avocado", "carrot", "olive"));
        for (int c = 0; c < Catalog.CATEGORIES.length; c++) {
            secs.put(String.valueOf(c), new ArrayList<Object>(Botany.sectionItems(c, mv)));
            haves.put(String.valueOf(c), Botany.have(c, mv, pk));
        }
        v.put("pantry", new ArrayList<Object>(pk)); v.put("sections", secs); v.put("have", haves);
        List<Object> bq = new ArrayList<Object>();
        for (String q : new String[]{"botanical fruits", "Botanic", "tomato"}) {
            Map<String, Object> o = new LinkedHashMap<String, Object>();
            o.put("q", q); o.put("labels", new ArrayList<Object>(PantryIndex.get().search(q, null).labels));
            bq.add(o);
        }
        v.put("search", bq);
        // v2.1 "Buy these next" expand / see all / sort (missing = required keys not in the pantry)
        {
            List<Recipe> recipes = Recipe.parseList(new String(Files.readAllBytes(new File(android, "assets/recipes.json").toPath()), StandardCharsets.UTF_8));
            Map<String, Cost.Price> defs = Cost.parseDefaults(new String(Files.readAllBytes(new File(android, "assets/prices.tsv").toPath()), StandardCharsets.UTF_8));
            String[] pan = {"chicken", "garlic", "onion", "rice", "egg", "salt", "black pepper", "olive oil", "butter", "flour", "milk", "sugar", "tomato", "potato"};
            Set<String> ps = new java.util.HashSet<String>();
            for (String x : pan) ps.add(Normalizer.normalize(x));
            List<String> ids = new ArrayList<String>(); List<List<String>> miss = new ArrayList<List<String>>(); Map<String, String> names = new LinkedHashMap<String, String>();
            for (Recipe r : recipes) {
                List<String> m = new ArrayList<String>();
                for (Ingredient i : r.ingredients) if (!i.optional && !i.key.isEmpty() && !ps.contains(i.key) && !m.contains(i.key)) { m.add(i.key); if (!names.containsKey(i.key)) names.put(i.key, i.name); }
                ids.add(r.id); miss.add(m);
            }
            List<BuyNext.Option> rk = BuyNext.ranked(ids, miss, names);
            Map<String, Cost.Price> user = new LinkedHashMap<String, Cost.Price>();
            user.put(rk.get(rk.size() - 1).key, Cost.make(0.05, 1, ""));
            List<Object> rr = new ArrayList<Object>(), cheap = new ArrayList<Object>();
            for (BuyNext.Option o : rk) { Map<String, Object> m = new LinkedHashMap<String, Object>(); m.put("key", o.key); m.put("name", o.name); m.put("alone", new ArrayList<Object>(o.alone)); m.put("closer", new ArrayList<Object>(o.closer)); m.put("why", BuyNext.why(o)); rr.add(m); }
            for (BuyNext.Option o : BuyNext.sort(rk, BuyNext.SORT_CHEAPEST, user, defs)) cheap.add(o.key);
            List<BuyNext.Pick> picks = BuyNext.suggest(ids, miss, names, BuyNext.MAX);
            List<Object> pw = new ArrayList<Object>();
            for (int i = 0; i < picks.size(); i++) { BuyNext.Option f = null; for (BuyNext.Option o : rk) if (o.key.equals(picks.get(i).key)) f = o; pw.add(BuyNext.whyPick(picks.get(i), i, f)); }
            List<Object> ct = new ArrayList<Object>();
            for (int i = 0; i < 12 && i < rk.size(); i++) { Cost.Price p = Cost.find(rk.get(i).key, null, defs); ct.add(p == null ? null : BuyNext.costText(p, Cost.money("$", p.price), i % 2 == 0)); }
            Map<String, Object> bn = new LinkedHashMap<String, Object>();
            bn.put("pantry", java.util.Arrays.asList((Object[]) pan)); bn.put("ranked", rr); bn.put("userPrice", rk.get(rk.size() - 1).key); bn.put("cheapest", cheap);
            bn.put("whyPick", pw); bn.put("costText", ct);
            v.put("buyNext", bn);
        }
        Files.write(new File(web, "tests/vectors21.json").toPath(), Json.write(v).getBytes(StandardCharsets.UTF_8));
        System.out.println("data21.js + vectors21.json written");
    }
}
