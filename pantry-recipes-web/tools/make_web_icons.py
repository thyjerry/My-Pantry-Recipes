#!/usr/bin/env python3
"""Builds the web app icons from the Android app's tools/make_icons.py render() and converts the
Android vector drawables (res/drawable/ic_*.xml) into js/icons.js. Usage: make_web_icons.py <android dir>"""
import os, re, sys, json
from PIL import Image, ImageDraw

android = sys.argv[1] if len(sys.argv) > 1 else "../pantry-recipes"
sys.path.insert(0, os.path.join(android, "tools"))
import make_icons as mk   # v1.8: the My Pantry Recipes mark (green circle + white leaf)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

def small(img, path):
    mk.save_small(img, path)

os.makedirs(os.path.join(out, "icons"), exist_ok=True)
# iOS and maskable icons must be opaque squares: flat brand green with the leaf inside the safe zone
small(mk.render(180, circle=False, bg=mk.GREEN, leaf_scale=0.86).convert("RGB"), os.path.join(out, "icons/apple-touch-icon.png"))
small(mk.render(192), os.path.join(out, "icons/icon-192.png"))
small(mk.render(512), os.path.join(out, "icons/icon-512.png"))
small(mk.render(512, circle=False, bg=mk.GREEN, leaf_scale=0.72).convert("RGB"), os.path.join(out, "icons/icon-maskable-512.png"))
small(mk.render(32), os.path.join(out, "icons/favicon-32.png"))
# header logo as inline SVG (circle + leaf), so it stays sharp and costs no image request
LOGO = ('<svg class="mark" viewBox="0 0 24 24" aria-hidden="true" focusable="false">'
        '<circle cx="12" cy="12" r="12" fill="#13AE48"/><path fill="#fff" d="' + mk.svg_path() + '"/></svg>')

# vector drawables -> {name: {vb, paths:[d...]}}
icons = {}
dd = os.path.join(android, "res/drawable")
for f in sorted(os.listdir(dd)):
    if not (f.startswith("ic_") and f.endswith(".xml")):
        continue
    x = open(os.path.join(dd, f)).read()
    vw = re.search(r'viewportWidth="([\d.]+)"', x).group(1)
    vh = re.search(r'viewportHeight="([\d.]+)"', x).group(1)
    paths = re.findall(r'pathData="([^"]+)"', x)
    icons[f[3:-4]] = {"vb": "0 0 %s %s" % (vw, vh), "d": paths}
with open(os.path.join(out, "js/icons.js"), "w") as fh:
    fh.write("/* Generated by tools/make_web_icons.py from the Android vector drawables (Material-style, Apache-2.0 shapes). */\n")
    fh.write("window.PR_ICONS = " + json.dumps(icons, separators=(",", ":")) + ";\n")
    fh.write("window.PR_LOGO = " + json.dumps(LOGO) + ";\n")
print("icons:", sorted(os.listdir(os.path.join(out, "icons"))), "svg:", len(icons))
