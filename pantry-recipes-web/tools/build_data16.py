#!/usr/bin/env python3
"""Writes js/data16.js from the Android assets foods.tsv (USDA FDC nutrition table) and prices.tsv (rough default prices)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
assets = os.path.join(here, '../../pantry-recipes/assets')
foods = open(os.path.join(assets, 'foods.tsv'), encoding='utf-8').read()
prices = open(os.path.join(assets, 'prices.tsv'), encoding='utf-8').read()
out = ('/* Generated by tools/build_data16.py - do not edit.\n'
       ' * foods: nutrient averages per 100 g from USDA FoodData Central SR Legacy (public domain).\n'
       ' * prices: rough hand-made default prices (USD ballpark), editable estimates. */\n'
       'window.PR_DATA16 = ' + json.dumps({'foods': foods, 'prices': prices}, ensure_ascii=False) + ';\n')
open(os.path.join(here, '../js/data16.js'), 'w', encoding='utf-8').write(out)
print('js/data16.js', len(out), 'bytes')
